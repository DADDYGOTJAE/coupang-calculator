  const storageKey = 'gotjae-live-kit-' + root.dataset.kit;
  let checked = {};
  try { checked = JSON.parse(localStorage.getItem(storageKey)) || {}; } catch(e) { checked = {}; }

  function esc(value){
    return String(value).replace(/[&<>"']/g, c => ({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
  }

  function itemKey(sectionIndex, itemIndex){
    return sectionIndex + '-' + itemIndex;
  }

  function totalItems(){
    return kit.sections.reduce((sum, section) => sum + section.items.length, 0);
  }

  function doneItems(){
    let done = 0;
    kit.sections.forEach((section, sectionIndex) => {
      section.items.forEach((_, itemIndex) => {
        if (checked[itemKey(sectionIndex, itemIndex)]) done += 1;
      });
    });
    return done;
  }

  function save(){
    try { localStorage.setItem(storageKey, JSON.stringify(checked)); } catch(e) {}
  }

